const fs = require("fs");
const path = require("path");

const root = path.resolve(path.dirname(__filename), "..");
const extDir = path.join(root, "extension");

const entries = [
  path.join(extDir, "shared-defaults.js"),
  path.join(extDir, "content.js"),
];

const outputPath = path.join(extDir, "content-classic.js");

function getImports(filePath) {
  const code = fs.readFileSync(filePath, "utf8");
  const regex = /import\s+[\s\S]*?from\s+['"]([^'"]+)['"];?/g;
  const imports = [];
  let m;
  while ((m = regex.exec(code))) {
    const spec = m[1];
    if (!spec.startsWith("./")) continue;
    const resolved = path.resolve(path.dirname(filePath), spec);
    if (fs.existsSync(resolved)) imports.push(resolved);
  }
  return imports;
}

const seen = new Set();
const ordered = [];

function walk(filePath) {
  if (seen.has(filePath)) return;
  seen.add(filePath);
  for (const imp of getImports(filePath)) {
    walk(imp);
  }
  ordered.push(filePath);
}

for (const entry of entries) {
  walk(entry);
}

const duplicateDeclared = new Set();

function stripExports(code) {
  return code.replace(/^export /gm, "");
}

function stripImports(code) {
  return code.replace(/import\s+[\s\S]*?from\s+['"][^'"]+['"];?/g, "");
}

function removeFunction(source, name) {
  const regex = new RegExp(`^function\\s+${name}\\s*\\(`, "gm");
  let match;
  while ((match = regex.exec(source)) !== null) {
    const startIdx = match.index;
    const braceIdx = source.indexOf("{", startIdx);
    if (braceIdx === -1) break;
    let depth = 1;
    let i = braceIdx + 1;
    const len = source.length;
    while (i < len && depth > 0) {
      const ch = source[i];
      if (ch === "{") depth++;
      else if (ch === "}") depth--;
      i++;
    }
    if (depth === 0) {
      source = source.slice(0, startIdx) + source.slice(i);
      regex.lastIndex = 0;
    } else {
      break;
    }
  }
  return source;
}

function processSource(source) {
  let processed = stripExports(stripImports(source));
  if (duplicateDeclared.has("BOC_VERSION")) {
    processed = processed.replace(/^const BOC_VERSION = "1\.1\.4";?$/gm, "");
  } else if (processed.match(/^const BOC_VERSION = "1\.1\.4";?$/m)) {
    duplicateDeclared.add("BOC_VERSION");
  }
  if (duplicateDeclared.has("normalizeNotePlaceholderSections")) {
    processed = removeFunction(processed, "normalizeNotePlaceholderSections");
  } else if (processed.match(/^function normalizeNotePlaceholderSections\(/m)) {
    duplicateDeclared.add("normalizeNotePlaceholderSections");
  }
  return processed;
}

const banner = [
  "// === GENERATED FILE ===",
  "// Source: extension/shared-defaults.js + extension/content.js",
  "// Build:   node scripts/build-content-classic.js",
  "// Do not edit this file directly; edit the source files instead.",
  "// =======================",
  ""
].join("\n");

const parts = ordered.map((file) => {
  const source = fs.readFileSync(file, "utf8");
  const processed = processSource(source);
  const rel = path.relative(extDir, file).replace(/\\/g, "/");
  return `// === ${rel} ===\n${processed.trim()}`;
});

fs.writeFileSync(outputPath, `${banner}${parts.join("\n\n")}\n`, "utf8");
console.log(`Wrote ${outputPath}`);